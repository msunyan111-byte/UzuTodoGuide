    private StandardChecklist() {
    }

    /**
     * 公開形態に応じた標準チェックリストを生成します。
     *
     * @param projectId 作品ID
     * @param releaseType 公開形態
     * @return 標準チェックリスト
     */
    static List<ChecklistItem> create(final UUID projectId, final ReleaseType releaseType) {
        final List<ChecklistItem> items = new ArrayList<>();
        int order = 1;
        for (final Definition definition : DEFINITIONS) {
            if (definition.paidOnly && releaseType != ReleaseType.PAID) {
                continue;
            }
            final ChecklistItem item = new ChecklistItem(
                    UUID.randomUUID(), projectId, definition.name, order);
            item.setDescription(definition.description);
            items.add(item);
            order++;
        }
        return items;
    }

    /**
     * 標準チェックリストの定義を表すクラスです。
     */
    private static final class Definition {

        /**
         * 項目名
         */
        private final String name;

        /**
         * 項目の説明
         */
        private final String description;

        /**
         * 有料公開時のみ表示する場合はtrue
         */
        private final boolean paidOnly;

        private Definition(final String name, final String description, final boolean paidOnly) {
            this.name = name;
            this.description = description;
            this.paidOnly = paidOnly;
        }
    }
